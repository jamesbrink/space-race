/** How many numbers each star takes in STARS. */
export const STAR_STRIDE = 6;

const ARCSEC = DEG / 3600;

/** A star's yearly motion as a vector in J2000 (radians a year, at right angles to its direction), from its place (degrees) and proper motion (arcseconds a year). */
export function starMotion(ra: number, dec: number, pmRa: number, pmDec: number): Vec3 {
  const [sa, ca, sd, cd] = [Math.sin(ra * DEG), Math.cos(ra * DEG), Math.sin(dec * DEG), Math.cos(dec * DEG)];
  const [a, d] = [pmRa * ARCSEC, pmDec * ARCSEC];
  return [-sa * a - ca * sd * d, ca * a - sa * sd * d, cd * d];
}

/** Toward a star in J2000 `years` after 2000.0 (before it: negative), as a unit vector: its catalogue place carried along its proper motion. */
export function starDirection(ra: number, dec: number, pmRa: number, pmDec: number, years: number): Vec3 {
  const [sa, ca, sd, cd] = [Math.sin(ra * DEG), Math.cos(ra * DEG), Math.sin(dec * DEG), Math.cos(dec * DEG)];
  const m = starMotion(ra, dec, pmRa, pmDec);
  return unit([ca * cd + m[0] * years, sa * cd + m[1] * years, sd + m[2] * years]);
}

