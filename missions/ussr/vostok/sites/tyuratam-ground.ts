/**
 * What the ground is round Site 1 where it is not the steppe's loam: the takyrs (bare clay pans), the salt crusts, the
 * sand and the old channels, where the maps and photographs place them. Metres east and north of Site 1's axis, out to
 * the land's edge 8 km off (viewer/tyuratam.ts draws them; beyond, the region's maps). A pan, a crust or a patch of sand
 * is a ring; a channel is its middle line and its breadth. Things under some 80 m across are not mapped and not drawn.
 *
 * `documented`: the General Staff's 1:100,000 sheet L-41-79 (state of 1974) or Krechetov and others' soil map of the
 * cosmodrome (2015) has the kind there, its outline traced off the photographs. `estimated`: read off the photographs
 * alone, a pale pan in December 1960 and still pale today taken for a takyr. `of`: '1961' seen on the Corona frames of
 * December 1960 and May 1962 and not today; 'today' on today's imagery only; 'both'. How each was read, and the frames'
 * ids: site-1.md, "The ground and what grows", and docs/sources.md. Made by the research of November 2026 from its pans.json.
 */
export interface GroundKind {
  kind: 'takyr' | 'salt' | 'sand' | 'channel';
  ring: [number, number][];
  /** A channel's breadth, m. */
  width?: number;
  of: '1961' | 'today' | 'both';
  confidence: Confidence;
  source: string;
}

